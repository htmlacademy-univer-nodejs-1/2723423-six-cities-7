import {Container} from 'inversify';
import {Model} from 'mongoose';
import {Application} from './app/application.js';
import {ConfigService} from './config/config-service.js';
import {CommentModelToken, FavoriteModelToken, OfferModelToken, UserModelToken} from './container.types.js';
import {DatabaseService} from './database/database-service.js';
import {LoggerService} from './logger/logger-service.js';
import {CommentDocument, CommentModel} from './modules/comment/comment.model.js';
import {CommentService} from './modules/comment/comment-service.js';
import {FavoriteDocument, FavoriteModel} from './modules/favorite/favorite.model.js';
import {FavoriteService} from './modules/favorite/favorite-service.js';
import {OfferDocument, OfferModel} from './modules/offer/offer.model.js';
import {OfferService} from './modules/offer/offer-service.js';
import {UserDocument, UserModel} from './modules/user/user.model.js';
import {UserService} from './modules/user/user-service.js';

const container = new Container();
container.bind(LoggerService).toSelf().inSingletonScope();
container.bind(ConfigService).toSelf().inSingletonScope();
container.bind(Application).toSelf();
container.bind(DatabaseService).toSelf().inSingletonScope();
container.bind<Model<UserDocument>>(UserModelToken).toConstantValue(UserModel);
container.bind<Model<OfferDocument>>(OfferModelToken).toConstantValue(OfferModel);
container.bind<Model<CommentDocument>>(CommentModelToken).toConstantValue(CommentModel);
container.bind<Model<FavoriteDocument>>(FavoriteModelToken).toConstantValue(FavoriteModel);
container.bind(UserService).toSelf();
container.bind(OfferService).toSelf();
container.bind(CommentService).toSelf();
container.bind(FavoriteService).toSelf();

export {container};
